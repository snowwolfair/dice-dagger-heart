import { Context } from "koishi";
import { ensureRule } from "./commandRule";
import { listenCommand } from "../utiles/listenCommand";

/** 注册 helpdh：列出 DH 规则下的全部可用指令 */
export function setHelp(ctx: Context) {
  listenCommand(ctx, "helpdh", async (session) => {
    if (!(await ensureRule(ctx, session, "DH"))) return;

    const lines = [
      " 匕首之心(DH)规则可用指令一览",
      "",
      "━━ 角色卡指令━━",
      "  pcnew <名称>              创建并登场角色（别名 nn）",
      "  gm                        创建主持人(GM)（每群限一位）",
      "  pcswitch <名称>           切换登场角色（别名 pccg）",
      "  pclist                    列出当前账号的所有角色（加任意参数列出全群）",
      "  showplayer                显示当前登场角色卡",
      "  pcattr [名称]             显示指定角色的属性文本",
      "  pcpc [名称]               重置当前或指定角色的属性",
      "  pcremove <名称>           删除指定角色（别名 pcmv）",
      "",
      "━━ 二元掷骰指令━━",
      "  .dd [调整值]              行动掷骰（希望D12 + 恐惧D12）",
      "    · 希望骰>恐惧骰  → 希望结果，角色+1希望",
      "    · 恐惧骰>希望骰  → 恐惧结果，GM+1恐惧点",
      "    · 两骰相等      → 关键成功，角色+1希望、-1压力",
      "    · 调整值可用：数字、骰子、属性名、优势/劣势、经历名",
      "        例：.dd +2+1d4",
      "        例：.dd 敏捷+优势",
      "  .ddr [调整值]             反应掷骰（不修改资源）",
      "",
      "━━ 普通掷骰━━",
      "  r / .r [表达式]           普通骰",
      "    · r                     掷 1d6",
      "    · r 1d6+2  /  .r1d6+2",
      "",
      "━━ 属性录入━━",
      "  .st <属性+值...>          录入属性（支持覆盖/增量两种模式）",
      "    · 短输入(≤20字) → 增量模式：.st 希望+1 压力-1 敏捷+1",
      "    · 长输入(>20字) → 覆盖模式：.st 敏捷1力量0灵巧1本能0风度0知识1生命6生命上限6",
      "    · 未识别的名称会存入「经历」栏",
      "    · 可用属性：敏捷/力量/灵巧/本能/风度/知识",
      "              生命/压力/希望/护甲/恐惧 及其「上限」",
      "              重伤阈值 / 严重阈值",
      "",
      "━━ 野兽饭━━",
      "  .cook                     开始烹饪（须带 . 或 。 前缀）",
      "    · 投入食材：1甜味+2酸味+4苦味",
      "    · 味道：甜味d4 咸味d6 苦味d8 酸味d10 鲜味d12 怪味d20",
      "    · 相同点数自动得分；无相同则输入 rm 味道 移除一颗",
      "",
      "━━ 通用━━",
      "  gugu on / off / leave     开启 / 关闭本群响应 / 退群",
      "  setrule [规则]            查看或切换规则集",
      "  log start [名称]          开始记录跑团日志",
      "  log p / r / end           暂停 / 恢复 / 结束并导出",
      "",
      "━━ 帮助与文档 ━━",
      "  helpdh                    显示本帮助",
    ];

    return lines.join("\n");
  });
}
